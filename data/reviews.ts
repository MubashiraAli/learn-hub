export function getReviewsForCourse(courseId: string): Review[] {
  return reviews.filter((review) => review.courseId === courseId);
}

export function getAverageRating(courseId: string): number {
  const courseReviews = getReviewsForCourse(courseId);
  if (courseReviews.length === 0) return 0;
  const total = courseReviews.reduce(
    (sum, review) => sum + review.rating,
    0,
  );
  return total / courseReviews.length;
}
